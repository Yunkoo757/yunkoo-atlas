import { _electron as electron } from 'playwright';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { Store } = require('../model.cjs');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'test-results');
fs.mkdirSync(output, { recursive:true });
const data = fs.mkdtempSync(path.join(os.tmpdir(), 'trainer-history-desktop-'));
const store = new Store(path.join(data, 'records'), () => new Date('2016-01-01T12:00:00Z'));
const id = store.create({ name:'长期记录分页验证', target:1000, daily:3 });
for (let i = 0; i < 150; i++) store.complete(id);
const env = { ...process.env, EXECUTION_TRAINER_DATA:data };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args:[root], env });
const errors = [];
try {
  const page = await app.firstWindow();
  page.on('pageerror', error => errors.push(error.message));
  await page.locator('#complete').waitFor();
  await page.evaluate(async () => { await Promise.all(document.getAnimations().map(a => a.finished.catch(() => {}))); });
  assert.equal(await page.locator('.day, .record').count(), 0);
  const before = await page.locator('#complete').boundingBox();
  await page.locator('#history > summary').click();
  await page.waitForFunction(() => document.querySelectorAll('.day').length === 100);
  await page.evaluate(async () => { await Promise.all(document.getAnimations().map(a => a.finished.catch(() => {}))); });
  await page.screenshot({ path:path.join(output, '09-long-history-days.png') });
  await page.locator('[data-more-days]').click();
  assert.equal(await page.locator('.day').count(), 200);
  await page.locator('#timestamps > summary').click();
  await page.waitForFunction(() => document.querySelectorAll('.record').length === 100);
  assert.equal((await page.locator('.record').first().textContent()).trim().startsWith('#150'), true);
  await page.locator('[data-more-times]').click();
  assert.equal(await page.locator('.record').count(), 150);
  assert.equal((await page.locator('.record').last().textContent()).trim().startsWith('#1'), true);
  assert.equal(await page.locator('[data-more-times]').count(), 0);
  await page.locator('#timestamps > summary').scrollIntoViewIfNeeded();
  await page.screenshot({ path:path.join(output, '10-long-history-times.png') });
  const ipc = await page.evaluate(async () => {
    const initial = await window.trainer.list();
    const unchanged = await window.trainer.list(initial.revision);
    return { initialTotal:initial.trainings[0].total, unchanged };
  });
  assert.equal(ipc.initialTotal, 150);
  assert.equal(ipc.unchanged.unchanged, true);
  assert.equal(Object.hasOwn(ipc.unchanged, 'trainings'), false);
  await page.locator('#complete').click();
  await page.waitForFunction(() => document.querySelector('.counter')?.textContent.trim() === '151 / 1000');
  assert.equal(await page.locator('#history').getAttribute('open'), '');
  assert.equal(await page.locator('#timestamps').getAttribute('open'), '');
  assert.equal(await page.locator('.day').count(), 200);
  assert.equal(await page.locator('.record').count(), 151);
  const after = await page.locator('#complete').boundingBox();
  assert.ok(Math.abs(after.width - before.width) < 0.5);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('#history > summary').click();
  await page.waitForFunction(() => document.querySelectorAll('.day, .record').length === 0);
  assert.deepEqual(errors, []);
  const result = { result:'passed', data, records:151, visibleDayLimit:200, ipc:ipc.unchanged, errors };
  fs.writeFileSync(path.join(output, 'history-verification.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} finally { await app.close(); }
